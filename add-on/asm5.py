check_debt_no_param_no_return()

# --------------------------------------------------
# ข้อ 5 - รูปแบบที่ 3: ฟังก์ชันมีพารามิเตอร์ ไม่คืนค่า
# --------------------------------------------------
print("\n--- ข้อ 5 รูปแบบที่ 3: ฟังก์ชันมีพารามิเตอร์ ไม่คืนค่า ---")
def check_debt_with_param_no_return(debts, threshold):
    for debt in debts:
        if debt > threshold:
            print(f"หนี้ {debt} บาท - แจ้งเตือน! ค่ามากกว่า {threshold}")
        else:
            print(f"หนี้ {debt} บาท - ปกติ")

check_debt_with_param_no_return(debts, 500)

# --------------------------------------------------
# ข้อ 5 - รูปแบบที่ 4: ฟังก์ชันมีพารามิเตอร์ มีการคืนค่า
# --------------------------------------------------
print("\n--- ข้อ 5 รูปแบบที่ 4: ฟังก์ชันมีพารามิเตอร์ มีการคืนค่า ---")
def check_debt_with_param_with_return(debts, threshold):
    alerts = []
    for debt in debts:
        if debt > threshold:
            alerts.append((debt, f"แจ้งเตือน! ค่ามากกว่า {threshold}"))
        else:
            alerts.append((debt, "ปกติ"))
    return alerts

result5 = check_debt_with_param_with_return(debts, 500)
for debt, status in result5:
    print(f"หนี้ {debt} บาท - {status}")